type CreateTestUserCmd struct {
	cmd  *cobra.Command
	Opts CreateTestUserOpts
	Env  env.Env
}

type CreateTestUserOpts struct {
	*util.GlobalOptions
	testuser.CreateTestUserOpts
	Vault        string
	VaultPrivKey string
	Timeout      time.Duration
}

// RunE creates and persists credentials using the selected cluster.
func (c *CreateTestUserCmd) RunE(command *cobra.Command, _ []string) error {
	if c.Opts.VaultPrivKey != "" && c.Opts.Vault == "" {
		return fmt.Errorf("--vault-priv-key requires --vault")
	}

	if c.Opts.Timeout <= 0 {
		return fmt.Errorf("timeout must be positive")
	}

	ctx, cancel := context.WithTimeout(command.Context(), c.Opts.Timeout)
	defer cancel()

	var (
		cfg *rest.Config
		err error
	)
	if c.Opts.Vault != "" {
		_, cfg, err = installer.VaultAndRESTConfig(c.Opts.Vault, c.Opts.VaultPrivKey, "sops", files.RootConfig{})
	} else {
		loading := clientcmd.NewNonInteractiveDeferredLoadingClientConfig(clientcmd.NewDefaultClientConfigLoadingRules(), &clientcmd.ConfigOverrides{})
		cfg, err = loading.ClientConfig()
	}

	if err != nil {
		return fmt.Errorf("loading Kubernetes config: %w", err)
	}

	c.Opts.Password = os.Getenv("OMS_CS_TEST_USER_PASSWORD")

	result, err := testuser.CreateTestUser(ctx, cfg, c.Opts.CreateTestUserOpts)
	if err != nil {
		return fmt.Errorf("failed to create test user: %w", err)
	}

	file, err := testuser.WriteResultToFile(result, c.Env.GetOmsWorkdir())
	if err != nil {
		return fmt.Errorf("saving test-user credentials: %w", err)
	}

	log.Printf("Test user credentials written to %s", file)
	log.Printf("Email:     %s", result.Email)
	log.Printf("Password:  %s", result.PlaintextPassword)
	log.Printf("API Token: %s", result.PlaintextAPIToken)
	return nil
}

func AddCreateTestUserCmd(parent *cobra.Command, opts *util.GlobalOptions) {
	c := &CreateTestUserCmd{
		cmd: &cobra.Command{
			Use:   "test-user",
			Short: "Create a test user through the internal Codesphere API",
			Long: io.Long(`Creates a test user through auth-service signup and sign-in, then creates an API token.

				Requires Kubernetes access to get services, list pods and create pods/portforward.
				Uses the current kubeconfig context (KUBECONFIG), or the kubeconfig stored in --vault.
				The service is accessed through a temporary loopback-only port-forward.

				For test installations with email signup/sign-in enabled, reCAPTCHA disabled and
				email confirmation disabled. OIDC-only installations are not supported. Application
				signup rules, including the allowed email domains, still apply.

				Email and a strong password are generated by default. Set --email and/or
				OMS_CS_TEST_USER_PASSWORD to override them. No pre-hashed password is needed.
				Credentials are displayed and saved as test-user.json in OMS_WORKDIR (default: ./oms-workdir).
				Each invocation creates a new user by default; this does not provision a custom test team.`),
		},
		Opts: CreateTestUserOpts{GlobalOptions: opts},
		Env:  env.NewEnv(),
	}
	c.cmd.RunE = c.RunE
	flags := c.cmd.Flags()
	flags.StringVar(&c.Opts.Namespace, "namespace", testuser.DefaultNamespace, "Namespace of the auth service")
	flags.StringVar(&c.Opts.Service, "auth-service", testuser.DefaultService, "Auth service name (override for host-suffixed development services)")
	flags.IntVar(&c.Opts.Port, "service-port", testuser.DefaultPort, "Auth service port")
	flags.StringVar(&c.Opts.Email, "email", "", "Email address (default: generated test+<random>@codesphere.com)")
	flags.StringVar(&c.Opts.Vault, "vault", "", "SOPS vault containing the target cluster kubeconfig (optional)")
	flags.StringVar(&c.Opts.VaultPrivKey, "vault-priv-key", "", "Age private key file for --vault (optional)")
	flags.DurationVar(&c.Opts.Timeout, "timeout", 2*time.Minute, "Overall timeout including port-forward setup")
	util.AddCmd(parent, c.cmd)
}
